_ANOMALY_GRADIENT = "linear-gradient(90deg, #c77f6d 0%, #e8eef0 50%, #159b91 100%)"


def _build_trend_layer(
    *,
    layer_id: str,
    name: str,
    short_name: str,
    description: str,
    data_source: str,
    product_id: str,
    variable: str,
    unit: str,
    native_spatial_resolution: str,
    temporal_resolution: str,
    cadence: ObservationGranularity,
    color_ramp: tuple[ColorRampStop, ...],
    value_range: ValueRange,
    legend_title: str,
    legend_unit: str,
    min_label: str,
    mid_label: str,
    max_label: str,
    gradient_css: str,
    nodata_label: str,
    tile_source_id: str,
    attribution: str,
    availability_status: DataAvailabilityStatus,
    supported_tile_formats: tuple[TileSourceFormat, ...],
    qa_policy: str,
    limitations: str,
) -> LayerDefinition:
    return LayerDefinition(
        id=layer_id,
        name=name,
        short_name=short_name,
        group_id="derived",
        description=description,
        data_source=data_source,
        product_id=product_id,
        product_version="v0.1",
        variable=variable,
        unit=unit,
        native_spatial_resolution=native_spatial_resolution,
        temporal_resolution=temporal_resolution,
        available_time_range=AvailableTimeRange("2001-01-01", "2025-12-31", cadence),
        attribution=attribution,
        availability_status=availability_status,
        rendering_type="raster",
        supported_tile_formats=supported_tile_formats,
        qa_policy=qa_policy,
        limitations=limitations,
        color_ramp=color_ramp,
        value_range=value_range,
        legend=LegendConfiguration(
            title=legend_title,
            unit=legend_unit,
            min_label=min_label,
            mid_label=mid_label,
            max_label=max_label,
            gradient_css=gradient_css,
            nodata_color="#d0dbe0",
            nodata_label=nodata_label,
            stops=color_ramp,
        ),
        tile_source=MapTileSource(
            id=tile_source_id,
            format="cog",
            url_template=None,
            crs="EPSG:4326",
            requires_backend_authorization=True,
            is_connected=False,
        ),
    )


